"""Generate LeanJinja2/RepoImpl/UnicodeTables.lean: the code points CPython's
`re` (the engine jinja2's urlize uses) counts as \\w, \\d and \\s.

The tables are measured, not copied: every scalar value is matched against
`re.fullmatch(r'\\w', c)` (and \\d, \\s) with the pinned interpreter, and the
accepted code points are written as sorted, disjoint ranges.

Run with: upstream-spec/.venv/bin/python -I scripts/unicode_tables.py
"""
import pathlib
import re
import sys
import unicodedata

OUT = pathlib.Path(__file__).resolve().parents[1] / "LeanJinja2/RepoImpl/UnicodeTables.lean"


def ranges(pattern):
    rx = re.compile(pattern)
    out, start = [], None
    for cp in range(0x110000):
        ok = not 0xD800 <= cp <= 0xDFFF and rx.fullmatch(chr(cp)) is not None
        if ok and start is None:
            start = cp
        if not ok and start is not None:
            out.append((start, cp - 1))
            start = None
    if start is not None:
        out.append((start, 0x10FFFF))
    return out


def table(name, doc, rs):
    body = ",\n  ".join(", ".join(f"({a:#x}, {b:#x})" for a, b in rs[i:i + 6]) for i in range(0, len(rs), 6))
    return f"/-- {doc} -/\ndef {name} : Array (Nat × Nat) := #[\n  {body}]\n"


def main():
    ver = sys.version.split()[0]
    parts = [
        "/-!\n# Unicode tables for regex `\\w`, `\\d` and `\\s`\n\n"
        f"Generated by `scripts/unicode_tables.py` from CPython {ver} `re` (Unicode\n"
        f"{unicodedata.unidata_version}), by matching every scalar value. Do not edit by hand.\n-/\n",
        "namespace LeanJinja2.UnicodeTables\n",
        table("word", "`\\w`: what `re` counts as a word character (`str.isalnum()` or `_`).", ranges(r"\w")),
        table("digit", "`\\d`: Unicode decimal digits.", ranges(r"\d")),
        table("space", "`\\s`: Unicode white space.", ranges(r"\s")),
        "end LeanJinja2.UnicodeTables\n",
    ]
    OUT.write_text("\n".join(parts))


main()
